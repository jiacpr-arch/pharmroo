export const GAME_SCENARIOS: GameScenario[] = [headacheWarfarin, childFeverDose, diarrheaAntibiotic, kneePainNsaidPpi];

export const GAME_SCENARIO_SLUGS: ReadonlySet<string> = new Set(GAME_SCENARIOS.map((s) => s.slug));

export function getBuiltinScenario(slug: string): GameScenario | null {
  return GAME_SCENARIOS.find((s) => s.slug === slug) ?? null;
}

/** slug ของเคสถัดไปในรายการ (วนกลับตัวแรกเมื่อถึงท้าย) */
export function nextScenarioSlug(slug: string): string {
  const i = GAME_SCENARIOS.findIndex((s) => s.slug === slug);
  const next = GAME_SCENARIOS[(i + 1) % GAME_SCENARIOS.length];
  return next.slug;
}
